import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

export function loadConfig() {
  const envPath = path.join(__dirname, ".env");
  if (fs.existsSync(envPath)) {
    const lines = fs.readFileSync(envPath, "utf8").split(/\r?\n/);
    for (const raw of lines) {
      const line = raw.trim();
      if (!line || line.startsWith("#")) continue;
      const eq = line.indexOf("=");
      if (eq === -1) continue;
      const key = line.slice(0, eq).trim();
      let val = line.slice(eq + 1).trim();
      if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
        val = val.slice(1, -1);
      }
      if (!process.env[key]) process.env[key] = val;
    }
  }

  const relayUrl = (process.env.RELAY_URL || "").replace(/\/+$/, "");
  const relayToken = process.env.RELAY_TOKEN || "";
  if (!relayUrl || !relayToken) {
    console.error("Missing RELAY_URL or RELAY_TOKEN. Please configure local-client/.env");
    process.exit(1);
  }
  return { relayUrl, relayToken, dir: __dirname };
}
